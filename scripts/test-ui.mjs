import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { mkdir, writeFile } from 'node:fs/promises';
await mkdir('test-output', { recursive: true });
const browser = await chromium.connectOverCDP('http://127.0.0.1:9225');
const page = browser.contexts()[0].pages().find(p => p.url().startsWith('dsh-app:'));
const errors = [];
page.on('pageerror', e => errors.push(e.message));
if (await page.locator('.ls-dialog[open]').count()) await page.getByRole('button', { name: '关闭对话框', exact: true }).click();
if (await page.locator('.ls-back').count()) await page.locator('.ls-back').click();
if (!(await page.locator('.ls-root').count())) await page.getByRole('button', { name: 'LaTeX Studio', exact: true }).click();
await page.waitForSelector('.ls-template-card', { timeout: 30000 });
const root = page.locator('.ls-root');
assert.equal(await root.locator('.ls-template-card').count(), 24);
await root.screenshot({ path: 'test-output/dsh-template-library.png' });
await root.getByRole('textbox', { name: '搜索模板' }).fill('Bioinformatics');
assert.ok(await root.locator('.ls-template-card').count() >= 3);
await root.getByRole('textbox', { name: '搜索模板' }).fill('');
await root.getByRole('button', { name: '生物与医学', exact: true }).click();
assert.equal(await root.locator('.ls-template-card').count(), 10);
await root.screenshot({ path: 'test-output/dsh-biology-templates.png' });
await root.getByRole('button', { name: '全部模板', exact: true }).click();
const picker = root.getByRole('combobox', { name: '打开已有文稿' });
const existing = picker.locator('option').filter({ hasText: 'LaTeX Studio Desktop Validation' }).first();
if (await existing.count()) await picker.selectOption(await existing.getAttribute('value'));
else {
  await root.getByRole('textbox', { name: '搜索模板' }).fill('IEEE');
  await root.locator('.ls-template-card').filter({ has: page.getByRole('heading', { name: 'IEEE 会议 · 双栏', exact: true }) }).click();
  await page.getByLabel('文稿标题', { exact: true }).fill('LaTeX Studio Desktop Validation');
  await page.getByRole('button', { name: '创建并开始写作', exact: true }).click();
}
await page.waitForSelector('.cm-editor', { timeout: 15000 });
await root.getByRole('button', { name: '公式', exact: true }).click();
await page.waitForFunction(() => !!customElements.get('math-field'));
await page.waitForFunction(() => document.querySelector('math-field')?.value === 'E = mc^2');
await root.screenshot({ path: 'test-output/dsh-equation-dialog.png' });
await page.getByRole('textbox', { name: 'LaTeX 代码', exact: true }).fill('x^2 + y^2 = z^2');
await page.getByRole('button', { name: '插入到光标位置', exact: true }).click();
await root.getByRole('button', { name: '保存修改', exact: true }).click();
await root.getByRole('button', { name: '编译 PDF', exact: true }).click();
await root.getByRole('button', { name: '编译 PDF', exact: true }).waitFor({ timeout: 90000 });
await page.waitForSelector('.ls-pdf-pages canvas', { timeout: 90000 });
const pages = await root.locator('.ls-pdf-pages canvas').count();
assert.ok(pages > 0);
await root.screenshot({ path: 'test-output/dsh-editor-pdf.png' });
await page.emulateMedia({ reducedMotion: 'reduce' });
const animation = await root.getByRole('button', { name: '公式', exact: true }).evaluate(el => getComputedStyle(el).transitionDuration);
assert.equal(animation, '1e-05s');
await page.emulateMedia({ reducedMotion: 'no-preference' });
const report = { testedAt: new Date().toISOString(), templates: 24, biology: 10, formulaControl: true, formulaInsertedAndCompiled: true, pdfPages: pages, reducedMotion: true, errors };
await writeFile('test-output/ui-results.json', JSON.stringify(report, null, 2));
console.log(JSON.stringify(report));
await browser.close();
assert.deepEqual(errors, []);
