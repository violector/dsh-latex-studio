import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const project = JSON.parse(await readFile('test-output/editor-project.json', 'utf8'));
const browser = await chromium.connectOverCDP('http://127.0.0.1:9225');
const page = browser.contexts()[0].pages().find(p => p.url().startsWith('dsh-app:'));
const cdp = await page.context().newCDPSession(page);
await cdp.send('Emulation.setDeviceMetricsOverride', { width: 1600, height: 1000, deviceScaleFactor: 1, mobile: false });
page.setDefaultTimeout(15000);
const errors = [];
page.on('pageerror', error => errors.push(error.message));
if (!(await page.locator('.ls-shell').count())) await page.getByRole('button', { name: 'LaTeX Studio', exact: true }).click();
if (await page.locator('.ls-back').count()) await page.locator('.ls-back').click();
await page.getByRole('combobox', { name: '打开已有文稿' }).selectOption(project.id);
await page.locator('.ls-chat [contenteditable=true]').waitFor();
const root = page.locator('.ls-root');
await root.locator('.cm-editor').waitFor();
await root.getByRole('button', { name: '恢复界面缩放', exact: true }).click();
for (const name of ['对话栏宽度', '目录栏宽度', '正文与 PDF 宽度']) await page.getByRole('separator', { name, exact: true }).dblclick();
const widths = () => page.locator('.ls-chat,.ls-files,.ls-editor-column,.ls-preview-column').evaluateAll(elements => elements.map(element => element.getBoundingClientRect().width));
const initial = await widths();
for (const [name, dx] of [['对话栏宽度', 70], ['目录栏宽度', 40], ['正文与 PDF 宽度', 65]]) {
  const handle = page.getByRole('separator', { name, exact: true });
  const bounds = await handle.boundingBox();
  await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2);
  await page.mouse.down(); await page.mouse.move(bounds.x + bounds.width / 2 + dx, bounds.y + bounds.height / 2, { steps: 12 }); await page.mouse.up();
}
const resized = await widths();
assert.ok(Math.abs(resized[0] - initial[0] - 70) < 2, 'Chat drag did not resize');
assert.ok(Math.abs(resized[1] - initial[1] - 40) < 2, 'File tree drag did not resize');
assert.ok(resized[2] > resized[3] + 90, 'Editor/PDF divider did not resize both panes');
const stored = await page.evaluate(() => JSON.parse(localStorage.getItem('latex-studio-layout:v1')));
await page.reload();
if (!(await page.locator('.ls-root').count())) await page.getByRole('button', { name: 'LaTeX Studio', exact: true }).click();
if (!(await root.locator('.cm-editor').count())) await page.getByRole('combobox', { name: '打开已有文稿' }).selectOption(project.id);
await root.locator('.cm-editor').waitFor();
assert.deepEqual(await page.evaluate(() => JSON.parse(localStorage.getItem('latex-studio-layout:v1'))), stored);
const restored = await widths();
for (let i = 0; i < restored.length; i++) assert.ok(Math.abs(restored[i] - resized[i]) < 2);
console.log('All four pane widths resize through real pointer dragging and survive reload.');

const sentence = 'This paragraph can be copied, deleted, or revised with AI.';
const textLine = root.locator('.cm-line').filter({ hasText: sentence });
await textLine.click({ clickCount: 3 });
await page.getByRole('toolbar', { name: '选区 AI 工具', exact: true }).waitFor();
assert.equal(await page.getByRole('textbox', { name: '选区修改要求' }).count(), 0);
assert.ok((await page.locator('.ls-selection-editor').boundingBox()).width < 140);
assert.ok(await root.locator('.cm-content').evaluate(el => el.contains(document.activeElement)), 'Compact AI control stole editor focus');
await page.locator('.ls-shell').screenshot({ path: 'test-output/compact-selection.png' });
await page.keyboard.press('Backspace');
assert.equal(await root.locator('.cm-line').filter({ hasText: sentence }).count(), 0);
await page.locator('.ls-selection-editor').waitFor({ state: 'detached' });
await page.keyboard.press('Control+z');
await textLine.waitFor();
await textLine.click({ clickCount: 3 });
await page.getByRole('button', { name: '展开 AI 选区修改', exact: true }).click();
await page.getByRole('dialog', { name: '修改选中文字', exact: true }).waitFor();
await page.getByRole('textbox', { name: '选区修改要求' }).fill('请保留原意，改成简洁的学术英语。');
await page.locator('.ls-shell').screenshot({ path: 'test-output/expanded-selection.png' });
await page.getByRole('button', { name: '收起选区修改', exact: true }).click();
await page.getByRole('toolbar', { name: '选区 AI 工具', exact: true }).waitFor();
await page.getByRole('button', { name: '关闭选区修改', exact: true }).click();
console.log('Compact selection control preserves typing/deletion; expanded editor opens on demand.');

const titleLine = root.locator('.cm-line').filter({ hasText: '\\section{Introduction}' });
const titleBounds = await titleLine.boundingBox();
const gutter = root.locator('.cm-foldGutter');
const gutterBounds = await gutter.boundingBox();
await page.mouse.click(gutterBounds.x + gutterBounds.width / 2, titleBounds.y + titleBounds.height / 2);
await root.locator('.cm-foldPlaceholder').waitFor();
assert.equal(await textLine.count(), 0);
assert.equal(await root.locator('.cm-line').filter({ hasText: '\\section{Methods}' }).count(), 1);
assert.equal(await readFile(join(project.directory, 'main.tex'), 'utf8'), project.source);
await page.locator('.ls-shell').screenshot({ path: 'test-output/section-folded.png' });
await root.locator('.cm-foldPlaceholder').first().click();
await textLine.waitFor();
for (const style of ['heading', 'environment', 'reference', 'setup', 'math', 'comment']) assert.ok(await root.locator(`.ls-syntax-${style}`).count(), `Missing ${style} highlighting`);
await root.getByRole('button', { name: '折叠', exact: true }).click();
await root.locator('.cm-foldPlaceholder').first().waitFor();
await root.getByRole('button', { name: '展开', exact: true }).click();
assert.equal(await root.locator('.cm-foldPlaceholder').count(), 0);
console.log('Gutter and toolbar folding work without changing source; semantic colors render.');

await root.locator('.cm-content').click();
await page.keyboard.press('Control+Equal');
await page.waitForFunction(() => getComputedStyle(document.querySelector('.ls-shell')).zoom === '1.1');
await page.keyboard.press('Control+Minus');
await page.waitForFunction(() => getComputedStyle(document.querySelector('.ls-shell')).zoom === '1');
await page.keyboard.press('Control+Minus');
await page.waitForFunction(() => getComputedStyle(document.querySelector('.ls-shell')).zoom === '0.9');
await page.keyboard.press('Control+Digit0');
await page.waitForFunction(() => getComputedStyle(document.querySelector('.ls-shell')).zoom === '1');
await root.getByRole('button', { name: '放大界面', exact: true }).click();
await textLine.click({ clickCount: 3 });
await page.getByRole('button', { name: '展开 AI 选区修改', exact: true }).click();
const popup = await page.locator('.ls-selection-editor').boundingBox();
assert.ok(popup.x >= 0 && popup.y >= 0 && popup.x + popup.width <= 1600 && popup.y + popup.height <= 1000, 'Zoom moved selection editor outside viewport');
await page.getByRole('button', { name: '关闭选区修改', exact: true }).click();
await root.getByRole('button', { name: '恢复界面缩放', exact: true }).click();
await page.waitForFunction(() => {
  const canvas = document.querySelector('.ls-preview-column .ls-pdf-pages canvas');
  if (!canvas?.width) return false;
  const data = canvas.getContext('2d').getImageData(0, 0, canvas.width, canvas.height).data;
  for (let i = 0; i < data.length; i += 40) if (data[i + 3] === 255 && data[i] < 180) return true;
  return false;
});
await page.locator('.ls-shell').screenshot({ path: 'test-output/resizable-workspace.png' });
console.log('Zoom shortcuts and zoomed popup positioning passed; PDF still renders after resizing.');
await writeFile('test-output/editor-ui-results.json', JSON.stringify({ testedAt: new Date().toISOString(), projectId: project.id, initialWidths: initial, resizedWidths: resized, persistedWidths: restored, compactSelection: true, deleteAndUndo: true, expandsOnDemand: true, sectionFolding: true, environmentHighlighting: true, zoomShortcuts: ['Ctrl +', 'Ctrl -', 'Ctrl 0'], errors }, null, 2));
await cdp.send('Emulation.clearDeviceMetricsOverride');
await browser.close();
assert.deepEqual(errors, []);
